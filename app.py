"""
Network Anomaly Detection using Machine Learning - live dashboard.

Run with:   streamlit run app.py
"""
import os
import time

import numpy as np
import pandas as pd
import streamlit as st

from anomaly_core import (
    ATTACK_TYPES,
    NUMERIC,
    Detector,
    evaluate,
    generate_flows,
    load_uploaded,
    roc_points,
    split_data,
)

HERE = os.path.dirname(os.path.abspath(__file__))
LOGO = os.path.join(HERE, "assets", "miet_logo.png")

st.set_page_config(page_title="Network Anomaly Detection", page_icon="🛡️", layout="wide")


# --------------------------------------------------------------------------
# Cached helpers
# --------------------------------------------------------------------------
@st.cache_data(show_spinner=False)
def make_synthetic(n, ratio, seed):
    return generate_flows(n=n, attack_ratio=ratio, seed=seed)


@st.cache_resource(show_spinner="Training model...")
def train_model(train_df, kind, n_estimators, seed):
    y = train_df["label"].values if "label" in train_df.columns else None
    return Detector(kind, n_estimators, seed).fit(train_df, y)


def metric_row(m):
    c = st.columns(5)
    c[0].metric("Precision", f"{m['precision']:.3f}", help="Of the alerts raised, how many were real attacks")
    c[1].metric("Recall", f"{m['recall']:.3f}", help="Of the real attacks, how many were caught")
    c[2].metric("F1-score", f"{m['f1']:.3f}")
    c[3].metric("False-positive rate", f"{m['fpr']:.3f}", help="Share of normal flows wrongly flagged")
    auc = m["auc"]
    c[4].metric("ROC-AUC", "n/a" if np.isnan(auc) else f"{auc:.3f}")


# --------------------------------------------------------------------------
# Sidebar
# --------------------------------------------------------------------------
with st.sidebar:
    if os.path.exists(LOGO):
        st.image(LOGO, width=140)
    st.markdown("**Arjun Saproo** (2024a1r058)  \n**Parth Kohli** (2024a1r052)")
    st.caption("Model Institute of Engineering and Technology, CSE")
    st.divider()

    st.subheader("1. Data")
    source = st.radio("Traffic source", ["Synthetic traffic generator", "Upload CSV"], label_visibility="collapsed")
    seed = st.number_input("Random seed", 0, 9999, 42)
    df = None
    if source == "Synthetic traffic generator":
        n_flows = st.slider("Number of flows", 2000, 20000, 8000, step=1000)
        ratio = st.slider("Attack share", 0.02, 0.40, 0.12, step=0.01)
        df = make_synthetic(n_flows, ratio, int(seed))
        data_key = f"syn-{n_flows}-{ratio}-{seed}"
    else:
        cic = st.checkbox("File is in CIC-IDS2017 format (best-effort converter)")
        up = st.file_uploader("CSV file", type=["csv"])
        st.caption("Own CSVs need the columns: protocol + " + ", ".join(NUMERIC) + " (optional: label).")
        if up is not None:
            try:
                df = load_uploaded(pd.read_csv(up), cic_format=cic)
                data_key = f"up-{up.name}-{up.size}-{cic}"
            except Exception as exc:  # noqa: BLE001
                st.error(f"Could not read file: {exc}")
    sample_path = os.path.join(HERE, "sample_flows.csv")
    if os.path.exists(sample_path):
        with open(sample_path, "rb") as fh:
            st.download_button("Download sample CSV (template)", fh.read(), "sample_flows.csv", "text/csv")

    st.subheader("2. Model")
    kind = st.radio(
        "Algorithm",
        [Detector.ISO, Detector.RF],
        format_func=lambda k: "Isolation Forest (unsupervised)" if k == Detector.ISO else "Random Forest (supervised)",
    )
    n_est = st.slider("Number of trees", 50, 300, 150, step=25)
    if kind == Detector.ISO:
        setting = st.slider(
            "Alert threshold (percentile of normal scores)", 0.90, 0.999, 0.97, step=0.001,
            help="Higher = fewer alerts and fewer false positives, but more missed attacks.",
        )
    else:
        setting = st.slider("Alert threshold (attack probability)", 0.10, 0.90, 0.50, step=0.05)

# --------------------------------------------------------------------------
# Header
# --------------------------------------------------------------------------
st.title("🛡️ Network Anomaly Detection using Machine Learning")
st.caption("Flow records → pre-processing → ML model → anomaly score → alert → analyst review")

if df is None:
    st.info("Upload a CSV in the sidebar, or switch to the synthetic traffic generator.")
    st.stop()

if source == "Synthetic traffic generator":
    st.warning(
        "Demo data is **synthetic** (generated by `anomaly_core.py`). Scores here show how the pipeline works; "
        "they are not claims about performance on real networks. Upload a real dataset such as CIC-IDS2017 for that."
    )

has_label = "label" in df.columns
if kind == Detector.RF and not has_label:
    st.error("Random Forest needs a labelled dataset. Choose Isolation Forest or upload a file with a label column.")
    st.stop()

train_df, test_df = split_data(df, 0.3, int(seed))
try:
    det = train_model(train_df, kind, n_est, int(seed))
except ValueError as exc:
    st.error(str(exc))
    st.stop()
thr = det.threshold(setting)
test_df = test_df.copy()
test_df["score"] = det.score(test_df)
test_df["alert"] = (test_df["score"] > thr).astype(int)

tab_data, tab_det, tab_alert, tab_live, tab_cmp = st.tabs(
    ["📊 Dataset", "🤖 Detection results", "🚨 Alerts", "📡 Live monitor", "⚖️ Model comparison"]
)

# --------------------------------------------------------------------------
# Dataset tab
# --------------------------------------------------------------------------
with tab_data:
    c = st.columns(4)
    c[0].metric("Flows", f"{len(df):,}")
    c[1].metric("Training flows", f"{len(train_df):,}")
    c[2].metric("Test flows", f"{len(test_df):,}")
    c[3].metric("Attack share", f"{df['label'].mean():.1%}" if has_label else "unlabelled")

    left, right = st.columns(2)
    with left:
        st.subheader("Traffic classes")
        if has_label:
            st.bar_chart(df["attack_type"].value_counts())
        else:
            st.write("No label column in this file.")
    with right:
        st.subheader("Feature distribution")
        feat = st.selectbox("Feature", NUMERIC, index=NUMERIC.index("conn_rate"))
        vals = np.log1p(df[feat].clip(lower=0))
        bins = np.linspace(vals.min(), vals.max(), 31)
        hist = pd.DataFrame(index=np.round(bins[:-1], 2))
        if has_label:
            for lab, name in [(0, "Normal"), (1, "Attack")]:
                hist[name] = np.histogram(vals[df["label"] == lab], bins=bins)[0]
        else:
            hist["All flows"] = np.histogram(vals, bins=bins)[0]
        st.bar_chart(hist)
        st.caption("x-axis: log(1 + value). Attacks sit far from normal traffic on several features.")
    st.subheader("Sample of flow records")
    st.dataframe(df.head(200))

# --------------------------------------------------------------------------
# Detection tab
# --------------------------------------------------------------------------
with tab_det:
    st.subheader(f"{kind} on held-out test data")
    if not has_label:
        st.info("Metrics need labels. See the Alerts tab for flagged flows.")
        st.metric("Alerts raised", int(test_df["alert"].sum()))
    else:
        m = evaluate(test_df["label"], test_df["score"], test_df["alert"])
        metric_row(m)
        a, b = st.columns(2)
        with a:
            st.markdown("**Confusion matrix**")
            cm = pd.DataFrame(
                [[m["tn"], m["fp"]], [m["fn"], m["tp"]]],
                index=["Actual normal", "Actual attack"],
                columns=["Predicted normal", "Predicted attack"],
            )
            st.table(cm)
            st.caption(
                f"{m['fp']} normal flows wrongly flagged (false positives) and {m['fn']} attacks missed (false negatives)."
            )
            if "attack_type" in test_df.columns:
                st.markdown("**Detection rate by attack type**")
                att = test_df[test_df["label"] == 1].groupby("attack_type")["alert"].mean().rename("detected")
                st.bar_chart(att)
        with b:
            st.markdown("**ROC curve**")
            fpr, tpr = roc_points(test_df["label"], test_df["score"])
            roc = pd.DataFrame({"False-positive rate": fpr, "True-positive rate": tpr}).set_index("False-positive rate")
            st.line_chart(roc)
            st.markdown("**Anomaly score distribution**")
            edges = np.linspace(test_df["score"].min(), test_df["score"].max(), 31)
            h = pd.DataFrame(index=np.round(edges[:-1], 3))
            h["Normal"] = np.histogram(test_df.loc[test_df["label"] == 0, "score"], bins=edges)[0]
            h["Attack"] = np.histogram(test_df.loc[test_df["label"] == 1, "score"], bins=edges)[0]
            st.bar_chart(h)
            st.caption(f"Alert threshold = {thr:.3f}. Flows to the right of it raise an alert.")

# --------------------------------------------------------------------------
# Alerts tab
# --------------------------------------------------------------------------
with tab_alert:
    alerts = test_df[test_df["alert"] == 1].sort_values("score", ascending=False)
    st.subheader(f"{len(alerts)} alerts raised on the test set")
    st.caption("Alerts are indicators for investigation, not proof of an attack. A human analyst decides.")
    top_n = st.slider("Show top N alerts", 5, 200, 25)
    shown = alerts.head(top_n).copy()
    shown["why flagged"] = det.reasons(shown)
    cols = ["timestamp", "src_ip", "protocol", "dst_port", "score", "why flagged"]
    if has_label:
        cols.append("attack_type")
    view = shown[cols].reset_index(drop=True)
    view["score"] = view["score"].round(3)
    view["analyst verdict"] = ""
    edited = st.data_editor(
        view,
        column_config={
            "analyst verdict": st.column_config.SelectboxColumn(
                "analyst verdict", options=["", "Confirmed attack", "False positive", "Needs more info"]
            )
        },
        disabled=cols,
    )
    st.download_button("Download alert report (CSV)", edited.to_csv(index=False), "alert_report.csv", "text/csv")

# --------------------------------------------------------------------------
# Live monitor tab
# --------------------------------------------------------------------------
with tab_live:
    st.subheader("Simulated live traffic monitor")
    st.write(
        "A stream of new flows arrives every second. Normal traffic dominates until the attack burst starts, "
        "then the anomaly score and alert count jump."
    )
    c = st.columns(5)
    ticks = c[0].slider("Duration (seconds)", 20, 90, 40)
    per_tick = c[1].slider("Flows per second", 20, 200, 60, step=10)
    burst_at = c[2].slider("Attack starts at second", 5, 60, 15)
    burst_len = c[3].slider("Attack length (s)", 3, 30, 10)
    burst_type = c[4].selectbox("Attack type", ATTACK_TYPES)
    speed = st.slider("Playback delay (seconds per tick)", 0.0, 1.0, 0.25, step=0.05)

    if st.button("▶ Start live monitoring", type="primary"):
        kpi = st.empty()
        chart_ph = st.empty()
        table_ph = st.empty()
        hist = []
        total_flows = total_alerts = 0
        recent = pd.DataFrame()
        for t in range(1, ticks + 1):
            in_burst = burst_at <= t < burst_at + burst_len
            batch = generate_flows(
                n=per_tick,
                attack_ratio=0.65 if in_burst else 0.02,
                seed=int(seed) * 1000 + t,
                attack_types=[burst_type] if in_burst else None,
            )
            sc = det.score(batch)
            fl = sc > thr
            total_flows += len(batch)
            total_alerts += int(fl.sum())
            hist.append({"second": t, "mean anomaly score": float(sc.mean()), "alerts": int(fl.sum())})
            if fl.any():
                new = batch[fl].assign(score=sc[fl].round(3))
                new["why flagged"] = det.reasons(new)
                recent = pd.concat([new, recent]).head(8)
            h = pd.DataFrame(hist).set_index("second")
            with kpi.container():
                k = st.columns(4)
                k[0].metric("Second", f"{t}/{ticks}")
                k[1].metric("Flows analysed", f"{total_flows:,}")
                k[2].metric("Alerts raised", total_alerts)
                k[3].metric("Status", "🔴 ATTACK SUSPECTED" if fl.sum() > max(3, 0.15 * len(batch)) else "🟢 Normal")
            with chart_ph.container():
                a, b = st.columns(2)
                a.markdown("**Mean anomaly score per second**")
                a.line_chart(h[["mean anomaly score"]])
                b.markdown("**Alerts per second**")
                b.bar_chart(h[["alerts"]])
            if len(recent):
                with table_ph.container():
                    st.markdown("**Latest alerts**")
                    st.dataframe(recent[["timestamp", "src_ip", "protocol", "dst_port", "score", "why flagged"]])
            time.sleep(speed)
        st.success("Simulation finished. Alerts are leads for an analyst to check, not automatic blocks.")

# --------------------------------------------------------------------------
# Model comparison tab
# --------------------------------------------------------------------------
with tab_cmp:
    st.subheader("Isolation Forest vs Random Forest (same split)")
    if not has_label:
        st.info("Comparison needs a labelled dataset.")
    else:
        rows = {}
        for k_name, k_setting in [(Detector.ISO, 0.97), (Detector.RF, 0.5)]:
            d2 = train_model(train_df, k_name, n_est, int(seed))
            s2 = d2.score(test_df)
            p2 = (s2 > d2.threshold(k_setting)).astype(int)
            rows[k_name] = evaluate(test_df["label"], s2, p2)
        res = pd.DataFrame(rows).T[["precision", "recall", "f1", "fpr", "auc"]].astype(float).round(3)
        res.columns = ["Precision", "Recall", "F1-score", "False-positive rate", "ROC-AUC"]
        st.dataframe(res)
        st.bar_chart(res[["Precision", "Recall", "F1-score", "False-positive rate"]].T)
        st.caption(
            "Default settings: Isolation Forest at the 97th percentile of normal scores, Random Forest at probability 0.5. "
            "The unsupervised model never sees attack labels, so it is expected to score lower than the supervised one."
        )
